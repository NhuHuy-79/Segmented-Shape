package com.nhuhuy.segmented_shape.constant

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Holds default corner radius values used across shape transformations.
 */
object DefaultSegmentedValue {
    /**
     * Large corner radius ([16.dp]) applied to exterior outer corners.
     */
    val large: Dp = 16.dp

    /**
     * Small corner radius ([8.dp]) applied to interior inner corners.
     */
    val small: Dp = 8.dp
}